    function pointInShape(x, y, shape) {
        if (shape.type === "rect") return x >= shape.x && x <= shape.x + shape.w && y >= shape.y && y <= shape.y + shape.h;
        if (shape.type === "ellipse") return ((x - shape.cx) / shape.rx) ** 2 + ((y - shape.cy) / shape.ry) ** 2 <= 1;
        let inside = false;
        const points = shape.points;
        for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
            const [xi, yi] = points[i], [xj, yj] = points[j];
            if (((yi > y) !== (yj > y)) && (x < (xj - xi) * (y - yi) / (yj - yi) + xi)) inside = !inside;
        }
        return inside;
    }

    function isWalkable(mapId, x, y, radiusX = 13, radiusY = 8) {
        const map = MAPS[mapId];
        if (!map) return false;
        const samples = [[0, 0]];
        for (let i = 0; i < 16; i++) {
            const angle = i / 16 * Math.PI * 2;
            samples.push([Math.cos(angle) * radiusX, Math.sin(angle) * radiusY]);
        }
        return samples.every(([dx, dy]) => map.ground.some(shape => pointInShape(x + dx, y + dy, shape)) && !map.obstacles.some(shape => pointInShape(x + dx, y + dy, shape)));
    }

